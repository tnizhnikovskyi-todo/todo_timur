def sheet_slot(i, j):
    """Стос у портальному складі: (code, індекс декору, кількість аркушів)."""
    decor = 5 if j >= 12 else (i * 3 + j * 5) % 7
    n = 0 if (i + 2 * j) % 11 == 0 else 5 * (2 + (i * 7 + j * 3) % 11)
    return f"PLT-{j + 1:02d}{chr(65 + i)}", decor, n


