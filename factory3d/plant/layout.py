def rack_slot(li, b, lv):
    """Стос у стелажі: (code, індекс декору, кількість аркушів) — li лінія 0.., b проліт 0.., lv ярус 0..3."""
    line = RACK_LINES[li][0]
    decor = (li * 2 + b * 3 + lv) % 7
    h = (li * 5 + b * 7 + lv * 3) % 13
    n = 0 if h in (0, 6) else 10 + 5 * (h % 8)
    return f"RCK-{line}-{b + 1}{chr(65 + lv)}", decor, n


def sheet_slot(i, j):
    """Стос у портальному складі: (code, індекс декору, кількість аркушів)."""
    decor = 5 if j >= 7 else (i * 3 + j * 5) % 7  # МДФ — біля нестингу
    n = 0 if (i + 2 * j) % 7 == 0 else 5 * (2 + (i * 7 + j * 3) % 11)
    return f"PLT-{j + 1:02d}{chr(65 + i)}", decor, n


def hw_state(ri, s, li):
    """Стан комірки фурнітури: ri — 0..5, s — 1..6, li — 1..4."""
    h = (ri * 7 + s * 3 + li * 5) % 23
    return "low" if h in (0, 1) else "out" if h == 2 else "ok"


def edge_slot(ui, s, li):
    """Полиця крайки: (індекс декору, кількість рулонів)."""
    return (ui + s + li) % len(EDGE_DECORS), (ui * 5 + s * 3 + li * 7) % 12


def fg_slot(ri, b, li):
    """Комірка складу ГП: (палет, шарів коробок на 1-й і 2-й палеті, індекс виробу)."""
    seed = (ri * 11 + b * 3 + li * 5) % 7
    n = 0 if seed in (0, 4) else (1 if seed == 3 else 2)
    return n, 2 + seed % 2, 2 + (seed + 1) % 2, (b + li + ri) % len(FG_PRODUCTS)


# Прямокутники, крізь які не можна ставити колони (заповнюються будівельниками)
OBST = []


def obst(x0, y0, x1, y1):
    OBST.append((min(x0, x1), min(y0, y1), max(x0, x1), max(y0, y1)))


def blocked(x, y, pad=0.4):
    return any(x0 - pad < x < x1 + pad and y0 - pad < y < y1 + pad for x0, y0, x1, y1 in OBST)
