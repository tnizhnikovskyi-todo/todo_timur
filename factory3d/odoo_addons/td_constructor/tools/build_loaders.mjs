#!/usr/bin/env node
// Збірка static/lib/f3d-loaders/f3d-loaders.esm.js (SPEC §8.1, DEC-06). Запускається РОЗРОБНИКОМ, не сервером; результат комітиться.
//
//   node tools/build_loaders.mjs [--three-dir <каталог розпакованого three@0.160.0/package>] [--esbuild-dir <каталог з node_modules/esbuild>]
//
// Без параметрів: `npm pack three@0.160.0` і `npm install esbuild` у тимчасовий каталог (потрібен доступ до npm-реєстру).
// У бандл входять OBJLoader, MTLLoader, STLLoader, FBXLoader, ColladaLoader, ThreeMFLoader, GLTFExporter і fflate (з examples/jsm/libs
// three r160, v0.6.9). `three` замінюється shim-модулем, що читає `globalThis.__F3D_THREE__` (його виставляє loadThree() із
// static/src/model/three.js): three.js не дублюється, усе працює з тими самими класами, що й бандл переглядача.
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import { mkdirSync, mkdtempSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const THREE_VERSION = "0.160.0";
const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, "../static/lib/f3d-loaders/f3d-loaders.esm.js");

const argv = process.argv.slice(2);
const arg = (name) => {
    const i = argv.indexOf(name);
    return i >= 0 ? resolve(argv[i + 1]) : null;
};
const run = (cmd, args, cwd) => execFileSync(cmd, args, { cwd, stdio: ["ignore", "pipe", "inherit"] }).toString();

const work = mkdtempSync(join(tmpdir(), "f3d-loaders-"));
let threeDir = arg("--three-dir");
if (!threeDir) {
    run("npm", ["pack", `three@${THREE_VERSION}`], work);
    run("tar", ["-xzf", `three-${THREE_VERSION}.tgz`], work);
    threeDir = join(work, "package");
}
let esbuildDir = arg("--esbuild-dir");
if (!esbuildDir) {
    esbuildDir = join(work, "esb");
    mkdirSync(esbuildDir, { recursive: true });
    run("npm", ["init", "-y"], esbuildDir);
    run("npm", ["install", "esbuild"], esbuildDir);
}
const esbuild = createRequire(join(esbuildDir, "noop.js"))("esbuild");
const pkg = JSON.parse(readFileSync(join(threeDir, "package.json"), "utf8"));
if (pkg.version !== THREE_VERSION) {
    throw new Error(`Очікується three@${THREE_VERSION}, знайдено ${pkg.version}`);
}

// shim: усі іменовані експорти three → властивості globalThis.__F3D_THREE__
const names = Object.keys(await import(pathToFileURL(join(threeDir, "build/three.module.js")).href)).filter((n) => /^[A-Za-z_$][\w$]*$/.test(n));
const shim =
    "const T = globalThis.__F3D_THREE__;\n" +
    "if (!T) throw new Error('f3d-loaders: globalThis.__F3D_THREE__ не виставлено (спершу loadThree())');\n" +
    names.map((n) => `export const ${n} = T.${n};`).join("\n") +
    "\n";

const j = (p) => join(threeDir, "examples/jsm", p);
const entry =
    [
        ["OBJLoader", "loaders/OBJLoader.js"],
        ["MTLLoader", "loaders/MTLLoader.js"],
        ["STLLoader", "loaders/STLLoader.js"],
        ["FBXLoader", "loaders/FBXLoader.js"],
        ["ColladaLoader", "loaders/ColladaLoader.js"],
        ["ThreeMFLoader", "loaders/3MFLoader.js"],
        ["GLTFExporter", "exporters/GLTFExporter.js"],
    ]
        .map(([n, p]) => `export { ${n} } from ${JSON.stringify(j(p))};`)
        .join("\n") + `\nexport * as fflate from ${JSON.stringify(j("libs/fflate.module.js"))};\n`;

const res = await esbuild.build({
    stdin: { contents: entry, resolveDir: threeDir, sourcefile: "f3d-loaders-entry.js" },
    bundle: true,
    format: "esm",
    target: "es2020",
    minify: true,
    legalComments: "none",
    write: false,
    banner: {
        js:
            "/*! f3d-loaders: OBJ/MTL/STL/FBX/Collada/3MF loaders + GLTFExporter + fflate 0.6.9 from three@" + THREE_VERSION + " examples/jsm " +
            "(MIT, (c) 2010-2023 three.js authors; fflate (c) 2023 Arjun Barrett, MIT). `three` -> globalThis.__F3D_THREE__. " +
            "Generated by tools/build_loaders.mjs; do not edit. */",
    },
    plugins: [
        {
            name: "three-shim",
            setup(b) {
                b.onResolve({ filter: /^three$/ }, () => ({ path: "three", namespace: "f3d-shim" }));
                b.onLoad({ filter: /.*/, namespace: "f3d-shim" }, () => ({ contents: shim, loader: "js" }));
            },
        },
    ],
});
let code = res.outputFiles[0].text;
// AC-05: у вихідниках модуля немає зовнішніх URL (рядки на кшталт XML-просторів імен ламаємо екрануванням)
code = code.replace(/https?:\/\//g, (m) => m.replace("//", "\\/\\/"));
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, code);
console.log(`${OUT}: ${(statSync(OUT).size / 1024).toFixed(0)} КБ, експортів three у shim: ${names.length}`);
